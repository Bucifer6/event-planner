#!/usr/bin/env node
// Generates src/messages.generated.ts: an explicit import map of messages/<locale>/<ns>.json.
// An explicit map (not fs globbing) is what works identically in the Next server runtime,
// the static export build and vitest.
//
// Adding a namespace = add messages/ro/<ns>.json and messages/en/<ns>.json. This script runs
// automatically before dev, build, typecheck and test of the apps and of @ed/i18n; run it by
// hand with `pnpm --filter @ed/i18n gen`. The output depends only on the file list, so
// concurrent runs write identical content.
import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const locales = ["ro", "en"];
const out = join(root, "src", "messages.generated.ts");

export function render() {
  const lines = [
    "// GENERATED by scripts/gen-messages.mjs from messages/<locale>/*.json — do not edit.",
    "// Regenerate: pnpm --filter @ed/i18n gen",
    "/* eslint-disable */",
  ];
  const maps = [];
  for (const locale of locales) {
    const files = readdirSync(join(root, "messages", locale))
      .filter((f) => f.endsWith(".json"))
      .sort();
    const entries = [];
    for (const file of files) {
      const ns = file.slice(0, -".json".length);
      if (!/^[A-Za-z][A-Za-z0-9]*$/.test(ns)) {
        throw new Error(
          `messages/${locale}/${file}: namespace file names must be alphanumeric (camelCase)`,
        );
      }
      const ident = `${locale}_${ns}`;
      lines.push(`import ${ident} from "../messages/${locale}/${file}";`);
      entries.push(`    ${JSON.stringify(ns)}: ${ident},`);
    }
    maps.push(`  ${locale}: {\n${entries.join("\n")}\n  },`);
  }
  lines.push("", "export const messagesByLocale = {", ...maps, "} as const;", "");
  return lines.join("\n");
}

const next = render();
let current = "";
try {
  current = readFileSync(out, "utf8");
} catch {
  // first run
}
if (current !== next) {
  const tmp = `${out}.${process.pid}.tmp`;
  writeFileSync(tmp, next);
  renameSync(tmp, out); // atomic: parallel runs never leave a half-written file
}
