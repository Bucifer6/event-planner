export type Stitchwork = keyof typeof stitchwork;

export function InvitationStitchwork({
  motif,
  repeat = 5,
  vertical = false,
}: {
  motif: Stitchwork;
  repeat?: number;
  vertical?: boolean;
}) {
  const { palette, cells } = stitchwork[motif];
  const width = Math.max(...cells.map((row) => row.length));
  return (
    <svg
      className="invitation-stitchwork"
      viewBox={
        vertical ? `0 0 ${cells.length} ${width * repeat}` : `0 0 ${width * repeat} ${cells.length}`
      }
      aria-hidden="true"
      shapeRendering="crispEdges"
    >
      {palette.map((color, index) => {
        const stitch = 'ARCD'[index];
        const commands: string[] = [];
        for (let tile = 0; tile < repeat; tile++) {
          cells.forEach((row, y) => {
            for (let x = 0; x < row.length; x++) {
              if (row[x] === stitch) {
                const column = tile * width + x;
                commands.push(vertical ? `M${y} ${column}h1v1h-1z` : `M${column} ${y}h1v1h-1z`);
              }
            }
          });
        }
        return <path key={stitch} d={commands.join('')} fill={color} />;
      })}
    </svg>
  );
}
